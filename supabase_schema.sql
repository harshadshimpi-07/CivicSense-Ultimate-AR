-- 1. Create Issues Table
CREATE TABLE IF NOT EXISTS public.issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_name TEXT NOT NULL,
    reporter_email TEXT NOT NULL,
    reporter_phone TEXT DEFAULT '',
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    location_label TEXT DEFAULT '',
    image_name TEXT NOT NULL,
    image_url TEXT DEFAULT '',
    department TEXT NOT NULL,
    severity TEXT NOT NULL DEFAULT 'Medium',
    status TEXT NOT NULL DEFAULT 'Reported',
    assigned_to TEXT DEFAULT '',
    authority_note TEXT DEFAULT '',
    source TEXT NOT NULL DEFAULT 'Citizen Web',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Create Status History Table (Audit Trail)
CREATE TABLE IF NOT EXISTS public.status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL REFERENCES public.issues(id) ON DELETE CASCADE,
    status TEXT NOT NULL,
    note TEXT DEFAULT '',
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Create Performance & Geospatial Indexes
CREATE INDEX IF NOT EXISTS idx_issues_status ON public.issues(status);
CREATE INDEX IF NOT EXISTS idx_issues_category ON public.issues(category);
CREATE INDEX IF NOT EXISTS idx_issues_department ON public.issues(department);
CREATE INDEX IF NOT EXISTS idx_issues_reporter_email ON public.issues(reporter_email);
CREATE INDEX IF NOT EXISTS idx_issues_created_at ON public.issues(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_status_history_issue_id ON public.status_history(issue_id);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.issues ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.status_history ENABLE ROW LEVEL SECURITY;

-- 5. Create RLS Policies for CivicSense
-- Allow anyone (public/anon) to read issues
DROP POLICY IF EXISTS "Allow public read access to issues" ON public.issues;
CREATE POLICY "Allow public read access to issues"
ON public.issues FOR SELECT
USING (true);

-- Allow anyone to submit new complaints
DROP POLICY IF EXISTS "Allow public insert to issues" ON public.issues;
CREATE POLICY "Allow public insert to issues"
ON public.issues FOR INSERT
WITH CHECK (true);

-- Allow updating complaints (status, severity, staff notes)
DROP POLICY IF EXISTS "Allow public update to issues" ON public.issues;
CREATE POLICY "Allow public update to issues"
ON public.issues FOR UPDATE
USING (true);

-- Allow reading status history
DROP POLICY IF EXISTS "Allow public read access to status_history" ON public.status_history;
CREATE POLICY "Allow public read access to status_history"
ON public.status_history FOR SELECT
USING (true);

-- Allow adding status history
DROP POLICY IF EXISTS "Allow public insert to status_history" ON public.status_history;
CREATE POLICY "Allow public insert to status_history"
ON public.status_history FOR INSERT
WITH CHECK (true);

-- 6. Setup Supabase Storage Bucket for Evidence Photos
INSERT INTO storage.buckets (id, name, public)
VALUES ('civicsense-uploads', 'civicsense-uploads', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage RLS Policies
DROP POLICY IF EXISTS "Public Access for civicsense-uploads" ON storage.objects;
CREATE POLICY "Public Access for civicsense-uploads"
ON storage.objects FOR SELECT
USING (bucket_id = 'civicsense-uploads');

DROP POLICY IF EXISTS "Public Upload for civicsense-uploads" ON storage.objects;
CREATE POLICY "Public Upload for civicsense-uploads"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'civicsense-uploads');

DROP POLICY IF EXISTS "Public Update for civicsense-uploads" ON storage.objects;
CREATE POLICY "Public Update for civicsense-uploads"
ON storage.objects FOR UPDATE
USING (bucket_id = 'civicsense-uploads');

-- ==============================================================================
-- Verification Query (Optional Check)
-- ==============================================================================
SELECT 'CivicSense database schema and storage bucket configured successfully!' AS result;
